"""results/SUMMARY.md: one table per experiment, every configuration, median
and min-max over the repeats, plus the settings every run shared. Generated;
do not edit by hand."""
from __future__ import annotations

import json
import statistics
from pathlib import Path

from . import analysis

COLUMNS = [
    ("primary_tps", "primary tx/s"),
    ("replica_tps", "replica tx/s"),
    ("peak_lag_s", "peak lag s"),
    ("total_s", "caught up after s"),
    ("catchup_s", "after load end (s)"),
    ("p_group_ratio", "primary tx/group"),
    ("r_group_ratio", "replica tx/group"),
    ("retried_tx", "retries"),
]


def _fmt(vals: list) -> str:
    vals = [v for v in vals if v is not None]
    if not vals:
        return "-"
    med = statistics.median(vals)
    if all(isinstance(v, int) for v in vals) or abs(med) >= 100:
        f = lambda x: f"{x:,.0f}"  # noqa: E731
    else:
        f = lambda x: f"{x:.1f}"  # noqa: E731
    return f"{f(med)}" + (f" <sub>({f(min(vals))}-{f(max(vals))})</sub>" if len(vals) > 1 and min(vals) != max(vals) else "")


def experiment_table(exp_dir: Path) -> str:
    plan = json.loads((exp_dir / "plan.json").read_text())
    sums = analysis.experiment_summaries(exp_dir)
    if not sums:
        return ""
    groups: dict[str, list[dict]] = {}
    for s in sums:
        groups.setdefault(analysis.config_key(s), []).append(s)
    first = json.loads((next(d for d in sorted(exp_dir.iterdir()) if (d / "meta.json").exists())
                        / "meta.json").read_text())
    lines = [f"## {exp_dir.name}: {plan.get('title', '')}", "",
             f"*{plan.get('question', '')}*", "",
             f"Measurement: **{plan.get('mode_of_measurement', 'live')}**; "
             f"repeats: **{plan.get('repeats')}**, interleaved. Base settings: `{json.dumps(plan.get('base', {}))}`.", "",
             f"Server: {first['replica'].get('version')}; host: {first['host'].get('platform')}, "
             f"{first['host'].get('host_cpus')} vCPU, {first['host'].get('host_mem_gb')} GB; baseline CPU limits "
             f"primary={first['host'].get('primary_cpus_limit')} replica={first['host'].get('replica_cpus_limit')}.", "",
             "| configuration | n | " + " | ".join(c[1] for c in COLUMNS) + " |",
             "|---|---|" + "---|" * len(COLUMNS)]
    for key in groups:
        runs = groups[key]
        lines.append(f"| `{key}` | {len(runs)} | " +
                     " | ".join(_fmt([r.get(c) for r in runs]) for c, _ in COLUMNS) + " |")
    pngs = sorted(p.name for p in exp_dir.glob("*.png"))
    if pngs:
        lines += ["", "Charts: " + ", ".join(f"[{p}]({exp_dir.name}/{p})" for p in pngs)]
    return "\n".join(lines) + "\n"


def write_report(results: Path) -> Path:
    parts = ["# Results summary (generated by `python -m lab report`)", "",
             "Medians across repeats, with observed ranges in parentheses. Definitions of every column are in "
             "[lab/analysis.py](../lab/analysis.py) and [the measurement notes](../docs/method.md). Raw samples "
             "for every run: `results/<experiment>/<run>/samples.csv`.", ""]
    for exp in sorted(d for d in results.iterdir() if (d / "plan.json").exists()):
        parts.append(experiment_table(exp))
    path = results / "SUMMARY.md"
    path.write_text("\n".join(parts))
    return path
